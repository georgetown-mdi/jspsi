#!/usr/bin/env node
// routeTree.gen.ts freshness check, run by static_checks.yaml on every PR.
//
// apps/web/src/routeTree.gen.ts is written by the TanStack Router codegen and
// checked in by design: typecheck, lint, build, and the web test suites all
// read it, so a fresh clone must have it before any generation step runs. The
// price of checking it in is that every web-tooling invocation rewrites it, so a
// copy that has drifted behind the pinned generator shows up as an unrelated
// modification in a branch that touched no route -- noise in a diff, and a dirty
// tree where a clean one is required.
//
// This check turns that drift into a build failure: it regenerates with the
// generator the lockfile pins and compares byte for byte, so a refresh lands as
// its own commit instead of riding along in someone else's.
//
// Two properties the implementation is built around:
//
//   1. NON-MUTATING. The working-tree bytes are read before the run and written
//      back whatever the outcome -- a check that left a regenerated file behind
//      would recreate the exact hazard it exists to remove. SIGINT/SIGTERM
//      restore too, since an ordinary teardown does not run on a signal; a
//      backup outside the repo covers the restore itself failing. The teardown
//      and the handlers alike are armed by scripts/lib/regenerationChecks.mjs.
//   2. FAILS CLOSED when the codegen did not run. The trigger is a real
//      web-tooling invocation (`vitest list` loads apps/web/vite.config.ts,
//      which runs the tanstackStart plugin's codegen -- the cheapest such
//      invocation, ~7s). A check that only diffed the file after that command
//      would pass forever, detecting nothing, if a future TanStack or vitest
//      release stopped generating on config load. So the file handed to the
//      codegen holds a PROBE line, and finding that line still there
//      afterwards is a failure rather than a pass: the generator was measured
//      to overwrite a probe-marked file whole, leaving none of it behind.
//
// The probe is appended rather than the file being moved aside, so the path
// never stops existing. A repo-wide reader running concurrently -- the egress
// scan over `git ls-files`, an editor, a typecheck -- sees a valid file with one
// extra trailing comment for the duration, instead of an ENOENT.
//
// What this check cannot see:
//   - It compares the working-tree copy against what the LOCALLY INSTALLED
//     generator produces, so it is only as good as the lockfile pin. It says
//     nothing about what another version of @tanstack/router-generator would
//     write, and a node_modules out of step with the lockfile makes it disagree
//     with CI. It also cannot tell a stale copy from a generator that changed
//     its output format -- both read as "differs", and both are answered the
//     same way, by committing the regenerated bytes.
//   - It says nothing about route CORRECTNESS: that the tree is what the app
//     needs, that no route file is missing or misnamed, that the routes resolve.
//     It asserts only that the checked-in bytes are the generated bytes.
//   - It drives one invocation path. Another entry point that reached the
//     codegen with a different plugin configuration is outside what this
//     measures.
//   - It cannot separate a stale route tree from a broken web config: an
//     invocation that fails for any other reason (an uncollectable test file, a
//     missing @psilink/core build) fails this check too, reported as a codegen
//     failure including the command's own output rather than as staleness.
//   - It is not concurrency-safe against another writer. A process running the
//     web tooling at the same time -- a live `npm run dev` -- races it for the
//     file, and can leave either copy in place.

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  firstDifferingLine,
  withRestoreOnSignal,
} from "./lib/regenerationChecks.mjs";

/** The generated file this check guards, relative to the repository root. */
export const ROUTE_TREE = "apps/web/src/routeTree.gen.ts";

// The invocation that regenerates it: the cheapest one that loads
// apps/web/vite.config.ts and so runs the tanstackStart plugin's codegen. Held
// as argv and joined for display so the command this runs and the command the
// failure messages tell a contributor to run cannot drift apart.
const REGENERATE_ARGV = [
  "npm",
  "exec",
  "--workspace",
  "apps/web",
  "--",
  "vitest",
  "list",
  "--project",
  "unit",
];

/** The regeneration invocation, as a contributor would type it. */
export const REGENERATE_COMMAND = REGENERATE_ARGV.join(" ");

/**
 * The marker appended to the copy the codegen is handed. Its survival is what
 * tells this check the codegen never ran; its wording is addressed to whoever
 * finds it in a committed file after a run was killed outright.
 */
export const PROBE =
  "psilink route tree freshness probe -- an interrupted `npm run check:routetree` left this line; regenerate the file";

const PROBE_LINE = `\n// ${PROBE}\n`;

/** Run the real codegen under `root`, throwing with its output on a non-zero exit. */
export function runCodegen(root) {
  const [command, ...args] = REGENERATE_ARGV;
  execFileSync(command, args, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

/**
 * Regenerate the route tree over a probe-marked copy and report whether the
 * generator reproduces the working-tree bytes, as `{ok, status, message}`. The
 * original bytes are always back in place when this returns; `regenerate` is
 * injectable so a test can drive the outcomes without paying for the real
 * codegen.
 *
 * Statuses: `fresh` (ok), `missing`, `codegen-failed`, `codegen-did-not-run`,
 * `stale`.
 */
export function checkRouteTreeFreshness({
  root,
  regenerate = runCodegen,
} = {}) {
  const file = resolve(root, ROUTE_TREE);
  if (!existsSync(file)) {
    return {
      ok: false,
      status: "missing",
      message: `${ROUTE_TREE} is absent. It is a checked-in generated file -- restore it with \`git checkout -- ${ROUTE_TREE}\`, or regenerate it with \`${REGENERATE_COMMAND}\`.`,
    };
  }

  const original = readFileSync(file);
  const backupDirectory = mkdtempSync(join(tmpdir(), "routetree-fresh-"));
  const backup = join(backupDirectory, "routeTree.gen.ts");
  writeFileSync(backup, original);

  const restore = () => {
    try {
      writeFileSync(file, original);
    } catch (cause) {
      throw new Error(
        `could not restore ${ROUTE_TREE}; the original copy is at ${backup}`,
        { cause },
      );
    }
    rmSync(backupDirectory, { recursive: true, force: true });
  };

  return withRestoreOnSignal(restore, () => {
    writeFileSync(file, Buffer.concat([original, Buffer.from(PROBE_LINE)]));
    try {
      regenerate(root);
    } catch (error) {
      const output = [error.stdout, error.stderr, error.message]
        .filter((part) => typeof part === "string" && part.trim() !== "")
        .join("\n")
        .trim();
      return {
        ok: false,
        status: "codegen-failed",
        message: `\`${REGENERATE_COMMAND}\` failed, so the route tree could not be regenerated and its freshness is unknown:\n\n${output}`,
      };
    }

    const regenerated = existsSync(file) ? readFileSync(file) : null;
    if (regenerated === null || regenerated.includes(PROBE)) {
      const symptom =
        regenerated === null
          ? "the file is gone"
          : "the probe line this check wrote is still there";
      return {
        ok: false,
        status: "codegen-did-not-run",
        message: `\`${REGENERATE_COMMAND}\` did not rewrite ${ROUTE_TREE} (${symptom}). This check means nothing unless that invocation runs the TanStack Router codegen, so it fails rather than pass a comparison it never made -- find an invocation that does regenerate the route tree and update REGENERATE_ARGV in scripts/check-routetree-fresh.mjs.`,
      };
    }

    if (regenerated.equals(original)) {
      return {
        ok: true,
        status: "fresh",
        message: `${ROUTE_TREE} matches what the pinned TanStack Router generator produces.`,
      };
    }

    const line = firstDifferingLine(
      original.toString("utf8"),
      regenerated.toString("utf8"),
    );
    return {
      ok: false,
      status: "stale",
      message: `${ROUTE_TREE} is not what the pinned TanStack Router generator produces (first difference at line ${line}). Left stale, it rewrites itself under the next web-tooling run and lands as an unrelated modification in whatever branch is checked out. Refresh it in its own commit:\n\n  ${REGENERATE_COMMAND}\n  git add ${ROUTE_TREE}`,
    };
  });
}

// CLI entry: only runs when invoked directly, so the test can import the
// functions without the process.exit.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const result = checkRouteTreeFreshness({ root });
  if (!result.ok) {
    console.error(`Route tree freshness check failed: ${result.message}`);
    process.exit(1);
  }
  console.log(`Route tree freshness check passed: ${result.message}`);
}
